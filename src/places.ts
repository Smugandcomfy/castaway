export const PLACES: Place[] = GROUPS.flatMap(([region, rows]) =>
  rows.map(([name, lat, lon]) => ({ name, region, lat, lon })),
);

export const REGIONS: string[] = GROUPS.map(([region]) => region);

/// Greenwich, used when nobody has chosen. It is the meridian the whole
/// coordinate system is measured from, so it is the one honest default.
export const DEFAULT_PLACE: Place = {
  name: "Greenwich, United Kingdom",
  region: "Europe",
  lat: 51.4779,
  lon: 0,
};

export function findPlace(name: string): Place | null {
  if (name === DEFAULT_PLACE.name) return DEFAULT_PLACE;
  return PLACES.find((p) => p.name === name) ?? null;
}
