/// Places, for the one thing on the Sky page that needs one.
///
/// A planet's ecliptic longitude is the same for every observer on Earth, so
/// most of this app never asks where you are. The Ascendant and Midheaven are
/// the exceptions: they depend on the local meridian and horizon, so they need
/// a latitude and a longitude.
///
/// Typed in rather than looked up. The browser's geolocation API is not
/// available to an app tile — a credentialless, opaque-origin iframe cannot
/// hold the permission — and a city list is friendlier than asking someone for
/// their coordinates anyway.
///
/// Coordinates are city-centre, to four decimals. Precision beyond that is
/// pointless here: an ascendant moves about one degree every four minutes of
/// time, and a degree of longitude is four minutes, so being a few kilometres
/// off a city centre is far below anything a reader would notice.

